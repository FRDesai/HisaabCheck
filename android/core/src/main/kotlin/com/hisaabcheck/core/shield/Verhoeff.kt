fun isValidVerhoeff(digits: String): Boolean {
    // /^\d+$/ in JavaScript: one or more ASCII digits and nothing else (not even a trailing line break).
    if (digits.isEmpty() || digits.any { it !in '0'..'9' }) return false
    var c = 0
    val a = digits.reversed().map { it - '0' }
    for (i in a.indices) c = D[c][P[i % 8][a[i]]]
    return c == 0
}
